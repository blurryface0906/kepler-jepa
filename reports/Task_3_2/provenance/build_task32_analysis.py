"""Generate descriptive analysis tables from frozen full GPU results only.

Run after summarize_task32.py; no thresholds, training or original artifacts
are modified. The surrounding scientific discussion is reviewed separately.
"""
import json
from pathlib import Path


def moment(value):
    if value['mean'] is None:
        return f"не определено ({value['undefined']}/{value['n']})"
    return f"{value['mean']:.9g} ± {value['sample_sd']:.3g}"


def number(value):
    return 'не определено' if value is None else f'{value:.9g}'


def table(headers, rows):
    return '\n'.join(['| '+' | '.join(headers)+' |',
                      '| '+' | '.join(['---']*len(headers))+' |',
                      *['| '+' | '.join(map(str,row))+' |' for row in rows]])


def build(folder):
    report=json.loads((folder/'exp2_circular_results.json').read_text(encoding='utf-8-sig'))
    s=json.loads((folder/'provenance/post_analysis_statistics.json').read_text(encoding='utf-8-sig'))
    if report.get('execution_completed') is not True or report['protocol']['smoke_test']:
        raise ValueError('A full completed experiment is required for analysis')
    checks=report['checks'];base=checks[:16];controls=checks[16:]
    lines=['# Task 3.2: OPF, согласование частот и научные контроли','',
           f"Полный GPU-прогон завершен. Основные критерии: **{sum(c['passed'] for c in base)}/16**; "
           f"контроли M0_Koopman: **{sum(c['passed'] for c in controls)}/2**. "
           f"Общая приемка: **{sum(c['passed'] for c in checks)}/18**, "
           f"`exit {0 if report['acceptance_passed'] else 1}`.",'',
           'Все 15 обучений M1/M2/M3 × seed 42–46 выполнены заново: 2000 шагов, B=256, CUDA. '
           'M0 и M0_Koopman заморожены. Локальные и контейнерные unit-тесты: 147 OK. '
           f"Продолжительность полного пайплайна: {report['elapsed_seconds']:.1f} с. "
           'Обучение/чекпойнты float32, оценка float64. Все средние и выборочные SD используют пять seed; '
           'неопределенные оценки сохраняются, без отбора успешных орбит.','',
           'Начать проверку удобно с этого разбора и [графика 300 dpi](figures/exp2_circular_regimes.png). '
           'Полные измерения: [JSON](exp2_circular_results.json), [табличный отчет](exp2_circular_report.md), '
           '[stdout](exp2_circular_stdout.txt). Конкретизации до прогона: '
           '[протокол](task3_2_protocol_notes.md).','',
           'Главный результат: M2 теперь проходит T3 и обе проверки H4 на всех пяти seed. '
           'Единственный непройденный основной критерий — M2 T4: короткое окно 64 точки '
           'нарушает порог ошибки наклона на всех пяти seed, тогда как 512 точек проходят. '
           'Заданный полный PASS не достигнут. M1 проходит свои ID-критерии; '
           'случайный M0_Koopman сохраняет норму и согласованность роллаутов, но проваливает '
           'частотный закон. Это отделяет встроенную устойчивость от выученной физической частоты.','',
           '## Приемка по каждому критерию','',
           table(['Критерий','Статус'],[[c['criterion'],'PASS' if c['passed'] else 'FAIL'] for c in checks]),'',
           '## ID: частотный закон, полный d=64, S3b_diff','']
    rows=[]
    for model in ['M0','M0_Koopman','M1','M2']:
        for regime in ['T1','T3','T4','T4_512']:
            r=s['frequency'][f'test_id_sub/{model}/{regime}']
            rows.append([model,regime,moment(r['slope']),moment(r['r2']),
                         number(r['slope_abs_error']['max']),number(r['r2']['min']),
                         f"{r['invalid_orbits']}/{r['n_orbits']}",number(r['max_abs_q_error']['max'])])
    lines += [table(['Модель','Режим','Наклон ± SD','R² ± SD','Max ошибка наклона',
                     'Min R²','Invalid','Max ошибка абсолютной частоты'],rows),'',
              'T4 оценивает обученные горизонты 1–64, T4_512 — горизонты 1–512. '
              'Каждый критерий T4 требует всех десяти записей seed×горизонт. '
              'q=ω̂/a⁻¹·⁵ при μ=1; последняя колонка — максимум абсолютной ошибки q по всем орбитам/seed. '
              'Проверки наклона и R² сами по себе не ограничивают абсолютную частоту.','',
              'У M1 худшая ID-ошибка абсолютной частоты составляет около 0.94% в T3/T4_512 '
              'и 1.06% в T4_64. У M2 — около 9.91% и 21.23% соответственно. '
              'Следовательно, даже пройденный частотный критерий M2 в T3 не означает '
              'точность абсолютной частоты уровня M1. Intercept, индивидуальные q и все '
              'поорбитные оценки сохранены в исходном JSON.','',
              '### T3 и T4_512 не являются независимыми подтверждениями','',
              'T3 вычисляется последовательными одношаговыми вызовами, а T4_512 — отдельными прямыми '
              'действиями на горизонт k. Частоты сети зависят только от радиусов латентных плоскостей; '
              'вращения сохраняют эти радиусы. Поэтому в точной арифметике P₁ᵏ(z)=Pₖ(z), '
              'даже когда частоты физически неверны. Сходство их частотных таблиц обусловлено архитектурой; '
              'это численная проверка реализации, а не две независимые проверки выученного закона. '
              'Замороженный M0_Koopman проверяет достаточность одной этой конструкции.','',
              '## H4: in-sample и train→test','']
    detail=[]
    for r in report['frequency_runs']:
        if r['model']=='M2' and r['split']=='test_id_sub' and r['method']=='S3b_diff' and r['regime'] in ('T4','T4_512'):
            passed=r['invalid']==0 and r['slope_abs_error'] is not None and r['r2'] is not None and r['slope_abs_error']<.05 and r['r2']>.99
            detail.append([r['seed'],r['regime'],number(r['slope']),number(r['slope_abs_error']),number(r['r2']),r['invalid'],'PASS' if passed else 'FAIL'])
    insertion=['### M2: отдельные горизонты и seed','',
               table(['Seed','Режим','Наклон','Ошибка наклона','R²','Invalid','Порог'],detail),'',
               'T4 на 64 точках является префиксом прямого T4_512, но PCA и частотная регрессия '
               'подгоняются заново на каждом окне. Поэтому равенство T3 и T4_512 не требует совпадения '
               'оценки частоты на коротком и длинном окне. Короткий T4 охватывает только 2.52 единицы '
               'между отсчетами, около 0.147 периода на медленном крае ID. Различия здесь показывают '
               'чувствительность процедуры оценки и представления к окну; они не выделяют отдельно '
               'ошибку предиктора и ошибку извлечения частоты. Для этого нужен согласованный контроль '
               'T1_64/T4_64 и прямое сравнение выданных частот с физическими на тех же чекпойнтах.','']
    idx=lines.index('## H4: in-sample и train→test')
    lines[idx:idx]=insertion
    rows=[]
    for model in ['M1','M2','M3']:
        for regime in ['T1','T3']:
            r=s['scale'][f'test_id_sub/{model}/{regime}']
            o=s['oos_scale'][f'test_id_sub/{model}/{regime}']
            rows.append([model,regime,moment(r['phase_norm_r2']),moment(r['axis_probe_r2']),
                         moment(r['state_norm_r2']),moment(o['oos_phase_norm_r2']),moment(o['oos_axis_probe_r2'])])
    lines += [table(['Модель','Режим','Phase R²','Axis R²','State-norm R²','OOS phase R²','OOS axis R²'],rows),'',
              'OOS-пробы подогнаны на всех 200 train-орбитах, отдельно для T1/T3. Коэффициенты и отбор '
              'постоянных столбцов заморожены перед оценкой ID/OOD; отрицательные test R² не обрезаются. '
              'Проверки приемки H4 по ТЗ используют in-sample показатели. OOS не имеет заданного порога '
              'приемки и служит отдельным измерением переноса проб.','',
              'Нулевые phase/state-norm R² у M3 характеризуют выбранный канал нормы, а не полное отсутствие '
              'информации о полуоси. Для численно постоянной целевой phase-нормы применяется явно '
              'сохраненная конвенция R²=0; обычный R² постоянной цели не определен. Метаданные a используются '
              'как метки диагностических проб, но не входят в JEPA-предиктор и его обучающие лоссы.','',
              '## OOD: объединенный диапазон и две подгруппы','']
    rows=[]
    for model in ['M0_Koopman','M1','M2','M3']:
        for split in ['test_ood','test_ood_inner','test_ood_outer']:
            r=s['frequency'][f'{split}/{model}/T3'];o=s['oos_scale'][f'{split}/{model}/T3']
            rows.append([model,split,moment(r['slope']),moment(r['r2']),
                         number(r['max_abs_q_error']['max']),moment(o['oos_axis_probe_r2']),
                         f"{r['invalid_orbits']}/{r['n_orbits']}"])
    lines += [table(['Модель','Сплит T3','Наклон ± SD','R² ± SD','Max ошибка q','OOS axis R²','Invalid'],rows),'',
              'Inner содержит все 25 орбит a∈[0.25,0.45], outer — все 25 орбит a∈[5.5,8]. '
              'Это заранее существующие диапазоны, без отбора по результатам. Объединенная регрессия '
              'может скрывать неверные зависимости внутри каждой группы. OOD остается диагностикой '
              'без заданного в ТЗ численного порога успешности. Самая медленная outer-орбита покрывает '
              'лишь около 0.144 периода в оценочной записи; конечность частотной оценки не гарантирует '
              'ее устойчивости на короткой дуге.','',
              'У M1 и M2 внутренний OOD-диапазон имеет положительный наклон вместо −1.5: '
              'примерно +0.967 и +0.937. Худшие абсолютные ошибки частоты достигают 78.9% и 85.3%. '
              'OOS axis R² равны примерно −6.76 и −13.15, хотя объединенные OOD R² выглядят высокими. '
              'Таким образом, перенос на малые радиусы не подтвержден; разделение диапазонов '
              'меняет содержательную интерпретацию объединенного показателя.','',
              '## Потери и встроенные инварианты','']
    rows=[]
    for model in ['M1','M2','M3']:
        r=s['last_training_batch'][model]
        rows.append([model,*[moment(r[key]) for key in ['total','direct','ar','temporal','factor_scale','coherence','orthogonality','isotropic']]])
    lines += [table(['Модель','Total','Direct','AR','Temporal','Factor-scale','Coherence','OPF','SIGReg'],rows),'',
              'Это средние по пяти последним обучающим батчам (шаг 2000), а не независимый validation-loss. '
              'В таблице регуляризаторы показаны до весов: OPF×0.2, factor-scale×0.25, coherence×0.1, '
              'SIGReg×1. Новый OPF усредняет 3072 корреляции после нормировки состояния; '
              'прежний расчет усреднял суммы по 12 парам факторов. При одинаковой предварительной '
              'обработке различие нормировки составляет 256 раз.','']
    rows=[]
    for model in ['M0_Koopman','M1','M2','M3']:
        r=s['predictor_diagnostics'][model]
        rows.append([model,*[number(r['all_splits'][key]['max']) for key in
                     ['norm_relative_drift_max','action_log_drift_max','ar_direct_relative_error_max']],
                     moment(r['id']['log_rate_variance_mean'])])
    lines += [table(['Модель','Max дрейф нормы','Max дрейф log-действий','Max T3/T4_512','ID дисперсия log-частот'],rows),'',
              'Норма, действия и композиция предиктора заданы архитектурой и не являются самостоятельно '
              'открытыми законами сохранения. Coherence — дополнительное предположение о согласовании '
              'частот всех 32 плоскостей, включая малоактивные. Общая сеть частот M2 использует действия '
              'всех четырех блоков, поэтому блочный Q не делает факторы независимыми.','',
              'Прохождение частотных и масштабных критериев не устанавливает независимость факторов: '
              'для межфакторной корреляции отдельный порог приемки не задан. Ненулевой OPF следует '
              'интерпретировать вместе с другими потерями; одна доля регуляризатора в total не доказывает '
              'причинное подавление полезной информации.','',
              'Coherence M2 на последнем train-батче остается ненулевым: около 0.0242 до веса 0.1; '
              'средняя дисперсия log-частот на ID — около 0.00908. Это мягкий штраф, который '
              'не гарантирует общей частоты всех плоскостей. Остаточное расхождение частот '
              'мотивирует дальнейшую диагностику короткого окна, но не устанавливает причину '
              'провала T4 без отдельного контроля.','',
              'M3 полностью переобучена в составе требуемых 15 запусков. Независимое сравнение '
              'чекпойнтов подтвердило побитное совпадение всех ее тензоров с Task 3.1 по каждому '
              'из пяти seed. Это согласуется с сохраненной архитектурой, целью и детерминированным '
              'обучением данного контроля; старые чекпойнты не использовались для инициализации.','',
              '## Границы выводов и следующие проверки','',
              'В Task 3.2 одновременно изменены OPF, temporal/scale, AR-нормировка, факторный масштаб '
              'и coherence. Улучшение такого набора не доказывает причинный вклад одного OPF. '
              'Для причинного вывода нужны отдельные заранее зафиксированные абляции. '
              'Отсутствие ошибок на выбранной ID-сетке также не устанавливает надежный перенос на OOD.','',
              'Следующим содержательным расширением могут стать эллипсы с одинаковой большой полуосью '
              'и разными эксцентриситетами: одинаковый период при меняющейся форме и неравномерной '
              'скорости. Круговое латентное представление при этом может оставаться корректным; '
              'нужно проверять физическое соответствие, период и движение вдоль орбиты, а не форму PCA. '
              'Для выводов о JEPA-Anything требуется отдельно воспроизвести и сопоставить ее оригинальный протокол.','',
              '## Воспроизводимость','',
              'Аудит выявил плохо обусловленные train-признаки нормы/скорости M0 в T3. '
              'Для seed 43 число обусловленности стандартизованного дизайна около 9.08·10¹¹; '
              'коэффициенты axis-пробы порядка ±4.85·10¹⁰ почти компенсируются. Повторная '
              'подгонка разными численными библиотеками меняет предсказания до 0.00274. '
              'Исходные оценки не изменены. Аудит отдельно проверяет применение сохраненных '
              'train-коэффициентов и расчет test R², а независимую переподгонку сопоставляет '
              'с учетом обусловленности; все обнаруженные случаи записаны в JSON аудита. '
              'Такие M0-пробы не следует трактовать как надежный физический декодер.','',
              'График проверен визуально: 6600×1860, 300 dpi, четыре сопоставленных фазовых '
              'портрета с собственными осями. В табличном отчете отдельный воспроизводимый '
              'шаг исправляет неэкранированные вертикальные черты в математических заголовках '
              'на abs(...); численные строки, JSON, веса и исходники GPU-прогона не изменяются. '
              'Квитанция форматирования хранится в provenance/markdown_formatting_receipt.json.','',
              '- [Локальные тесты](task3_2_unit_tests.txt), [тесты контейнера](task3_2_gpu_unit_tests.txt).',
              '- [JSON всех оценок](exp2_circular_results.json), [полный отчет](exp2_circular_report.md), [stdout](exp2_circular_stdout.txt).',
              '- [Независимый аудит](provenance/artifact_audit.json), [статистики анализа](provenance/post_analysis_statistics.json).',
              '- [Пересчет статистик](provenance/summarize_task32.py), [построение таблиц этого разбора](provenance/build_task32_analysis.py).',
              '- 15 чекпойнтов float32 на шаге 2000 сохранены локально и исключены из Git. '
              '79 файлов прежних Task 3/Task 3.1 защищены контрольными суммами и сохранены неизменными.','']
    return '\n'.join(lines)


if __name__=='__main__':
    folder=Path(__file__).resolve().parents[1]
    (folder/'task3_2_analysis.md').write_text(build(folder),encoding='utf-8')
